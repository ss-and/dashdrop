export const PREFECTURES: Prefecture[] = RAW.map(([code, name, col, row]) => ({
  code,
  name,
  short: shorten(name),
  col,
  row,
}));

/**
 * 表記ゆれを吸収して都道府県を引く。
 *
 * 実データで見る形は「東京都」「東京」「 東京都 」（前後の空白）、
 * 全角空白入り、などいろいろある。カタカナやローマ字までは面倒を見ない——
 * 当たらなかった値は数だけ黙って捨てるのではなく、画面に「◯件が
 * 都道府県として読めませんでした」と実例つきで出して、人に直してもらう。
 * 推測で当てにいくと、間違って当てたときに気づけない。
 */
const LOOKUP = new Map<string, Prefecture>();
for (const p of PREFECTURES) {
  LOOKUP.set(p.name, p);
  LOOKUP.set(p.short, p);
  LOOKUP.set(p.code, p);
}

export function findPrefecture(raw: unknown): Prefecture | null {
  if (raw === null || raw === undefined) return null;
  const s = String(raw)
    // 全角空白も含めて落とす。Excel の住所列には普通に混ざっている。
    .replace(/[\s　]/g, "")
    .trim();
  if (s === "") return null;
  const hit = LOOKUP.get(s);
  if (hit) return hit;
  /*
   * 住所そのもの（「東京都渋谷区…」）が入っている列も多い。先頭が
   * 都道府県名で始まるなら、そこだけを採る。**含まれていれば良い**に
   * すると「京都」が「東京都渋谷区」に引っかかるので、必ず前方一致で見る。
   */
  for (const p of PREFECTURES) {
    if (s.startsWith(p.name)) return p;
  }
  return null;
}
