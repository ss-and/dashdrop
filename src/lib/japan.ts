/**
 * 都道府県。地図ウィジェットのための対応表と、名前の突き合わせ。
 *
 * ## なぜ本物の輪郭ではなく「タイル」なのか
 *
 * 実際の海岸線を描くには、簡略化しても 100KB を超える座標データを同梱する
 * ことになる。それだけの重さを払っても、**数値を読む道具としてはむしろ悪化する**：
 *
 *  - 東京都は面積で北海道の 260 分の1。売上の8割が東京でも、地図の上では
 *    ほぼ点にしかならない。面積の大小が、数字の大小を打ち消してしまう。
 *  - 小さい県は押せない。ドリルダウンしたい相手ほどクリックしづらい。
 *
 * タイル（1県 = 1マス）なら、どの県も同じ面積・同じ押しやすさで、濃淡だけが
 * 量を表す。選挙報道の地図が同じ形をしているのはこの理由による。
 * 地理そのものを見せたいのではなく、**都道府県別の量**を見せたいので、
 * ここではタイルを選ぶ。
 *
 * 並びは近似で、隣接関係は正確ではない（島根と鳥取の東西など、詰めるために
 * 妥協した箇所がある）。地方のまとまり——北海道・東北・関東・中部・近畿・
 * 中国・四国・九州・沖縄——が形で分かることを優先している。
 */

export interface Prefecture {
  /** JIS の都道府県コード（"01"〜"47"）。 */
  code: string;
  /** 正式名。「東京都」「北海道」「大阪府」。 */
  name: string;
  /** 接尾辞を落とした形。「東京」「北海道」「大阪」。突き合わせに使う。 */
  short: string;
  /** タイルの位置（左からの列・上からの行）。 */
  col: number;
  row: number;
}

/** タイルの盤面の大きさ。SVG の viewBox を決めるのに使う。 */
export const GRID_COLS = 13;
export const GRID_ROWS = 13;

/** 接尾辞を落とす。北海道だけは落とすと「北海」になるので除く。 */
function shorten(name: string): string {
  if (name === "北海道") return name;
  return name.replace(/[都府県]$/, "");
}

